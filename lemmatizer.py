"""
Лематизація української мови для пошуку (spільна для shipper та ui).

НАВІЩО. Manticore не має uk-стемера, а stem_ru українські флексії не стягує
(чергування голосних у корені: вразлив-ІСТЬ / вразлив-ОСТІ). Наслідок — запит
«вразливість» не знаходив «вразливості».

ЯК. Зводимо КОЖЕН україномовний токен до нормальної форми (леми) через
pymorphy3. Робимо це ОДНАКОВО на індексації (shipper кладе лему в content) і на
запиті (ui лематизує ввід перед MATCH) — тоді будь-яка словоформа з обох боків
зводиться до спільної леми й матчиться.

Латиницю НЕ чіпаємо: англ. словоформи (vulnerability/vulnerabilities) стягує
морфологія stem_en самого Manticore. Пропускати латинь крізь uk-аналізатор
шкідливо — він лематизував би її за укр. правилами.

Аналізатор важкий на створення (вантажить словник) — тримаємо ліниво-кешований
синглтон на процес.
"""

from __future__ import annotations

import re
from functools import lru_cache

# Максимальна довжина ПОШУКОВОГО ЗАПИТУ, що йде в морфоаналізатор. Дзеркалить
# MAX_QUERY_LEN із search_utils (512), але застосовується РАНІШЕ — бо там
# обрізання відбувається вже після лематизації, тобто запізно: parse() встиг би
# відпрацювати на всьому вводі. Стосується ЛИШЕ запиту, не тіл документів.
MAX_QUERY_CHARS = 512

# Токен-слово (літери/цифри/підкреслення, Unicode).
_WORD_RE = re.compile(r"\w+", re.UNICODE)
# Чи містить токен бодай одну кириличну літеру -> вважаємо україномовним.
_CYRILLIC_RE = re.compile(r"[Ѐ-ӿ]")


@lru_cache(maxsize=1)
def _analyzer():
    """Лінивий синглтон MorphAnalyzer(uk). Імпорт усередині — щоб сам модуль
    імпортувався навіть там, де pymorphy3 не встановлено (аж до першого виклику)."""
    import pymorphy3

    return pymorphy3.MorphAnalyzer(lang="uk")


@lru_cache(maxsize=100_000)
def _lemma(word: str) -> str:
    """Лема одного кириличного токена (кеш — багато повторів у корпусі CTI)."""
    return _analyzer().parse(word)[0].normal_form


def lemmatize_text(text) -> str:
    """Повертає текст, де КОЖЕН кириличний токен зведено до леми, а латиниця й
    пунктуація лишаються незмінними. Порожній/None -> ''."""
    if not text:
        return ""

    def repl(match: "re.Match") -> str:
        token = match.group(0)
        if _CYRILLIC_RE.search(token):
            return _lemma(token)
        return token

    return _WORD_RE.sub(repl, str(text))


def lemmatize_query(text) -> str:
    """Лематизація ПОШУКОВОГО ЗАПИТУ: спершу ріже ввід до MAX_QUERY_CHARS, і аж
    потім лематизує.

    Навіщо окрема функція: тіла документів (shipper) треба лематизувати ЦІЛКОМ,
    інакше повнотекстовий індекс втратить хвіст тексту. А ось запит користувача
    обмежений і так (search_utils.MAX_QUERY_LEN) — тільки там обрізання настає
    вже після морфоаналізу, тож морфоаналізатор встиг би прожувати весь ввід.
    Тут ріжемо ДО нього."""
    if not text:
        return ""
    return lemmatize_text(str(text)[:MAX_QUERY_CHARS])
